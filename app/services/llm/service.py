"""Adaptive ESM LLM Orchestration Service."""

import logging
from typing import Optional
from app.schemas.survey_config import SurveyConfig
from app.schemas.survey_response import SurveyResponseRecord, FollowUpSurveyPayload
from app.services.llm.base import BaseLLMProvider

logger = logging.getLogger("simple_surveys.llm.service")


class LLMService:
    """
    Coordinates prompt preparation, timeout protection,
    and schema-constrained follow-up survey creation.
    """

    def __init__(self, provider: BaseLLMProvider):
        self._provider = provider

    async def generate_adaptive_followup(
        self,
        survey: SurveyConfig,
        response_record: SurveyResponseRecord,
        round_number: int,
        photo_bytes: Optional[bytes] = None,
    ) -> Optional[FollowUpSurveyPayload]:
        """
        Orchestrates generative follow-up synthesis for an adaptive survey submission.
        Guarantees that errors, timeouts, or invalid model output return None gracefully
        without breaking the response submission flow.
        """
        if not survey.adaptive_followup or not survey.adaptive_followup.enabled:
            return None

        cfg = survey.adaptive_followup
        max_questions = cfg.max_questions_per_round or 1
        researcher_prompt = cfg.researcher_prompt

        try:
            researcher_message, questions = await self._provider.generate_followup_questions(
                survey_title=survey.title,
                response_record=response_record,
                photo_bytes=photo_bytes,
                max_questions=max_questions,
                system_instruction=researcher_prompt,
            )

            if not questions:
                logger.info(
                    "No valid follow-up questions generated by LLM for survey '%s', response '%s'.",
                    survey.survey_id,
                    response_record.response_id,
                )
                return None

            return FollowUpSurveyPayload(
                parent_response_id=response_record.response_id,
                survey_id=survey.survey_id,
                round_number=round_number,
                title="Follow-up Questions",
                researcher_message=researcher_message,
                questions=questions,
            )
        except Exception as e:
            logger.warning(
                "Adaptive follow-up generation failed for survey '%s': %s",
                survey.survey_id,
                e,
                exc_info=True,
            )
            return None
